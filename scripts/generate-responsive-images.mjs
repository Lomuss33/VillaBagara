import {execFileSync} from 'node:child_process'
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'
import {imageDimensions} from './lib/image-dimensions.mjs'

const workspace = fileURLToPath(new URL('../', import.meta.url))
const npmCLI = process.env.npm_execpath || join(dirname(process.execPath), 'node_modules/npm/bin/npm-cli.js')
if(!existsSync(npmCLI)) throw new Error('Run this generator with npm run images:responsive.')

// Keep the source list explicit; do not convert unrelated assets or gallery maps.
const source = 'images/villa_bagara/estate/front-porch.png'
const full = 'images/villa_bagara/estate/front-porch.webp'
const input = join(workspace, 'public', source)
const dimensions = imageDimensions(readFileSync(input))
if(!dimensions) throw new Error(`Cannot read source dimensions: ${source}`)
if(dimensions.width < 960) throw new Error('The estate source must be at least 960px wide.')

const variants = []
const widths = [...new Set([480, 960, dimensions.width])].sort((a, b) => a - b)
for(const width of widths) {
    const src = width === dimensions.width ? full : `images/villa_bagara/estate/front-porch-${width}.webp`
    const output = join(workspace, 'public', src)
    execFileSync(process.execPath, [npmCLI, 'exec', '--yes', '--package=sharp-cli@6.1.0', '--',
        'sharp', '-i', input, '-o', output, '-f', 'webp', '-q', '85',
        'resize', String(width), '--withoutEnlargement'], {cwd: workspace, stdio: 'inherit'})
    const bytes = readFileSync(output)
    const actual = imageDimensions(bytes)
    if(!actual || actual.width !== width) throw new Error(`Unexpected output dimensions: ${src}`)
    variants.push({src, ...actual})
    console.log(`${src}: ${actual.width}x${actual.height}, ${bytes.length} bytes`)
}

const manifest = {[full]: {...dimensions, variants}}
const share = join(workspace, 'public/images/villa_bagara/estate/share.jpg')
execFileSync(process.execPath, [npmCLI, 'exec', '--yes', '--package=sharp-cli@6.1.0', '--',
    'sharp', '-i', input, '-o', share, '-f', 'jpeg', '-q', '80',
    'resize', '1200', '--withoutEnlargement'], {cwd: workspace, stdio: 'inherit'})
console.log(`Social image: ${readFileSync(share).length} bytes`)
const manifestPath = join(workspace, 'src/data/generated/imageManifest.generated.js')
mkdirSync(dirname(manifestPath), {recursive: true})
writeFileSync(manifestPath, '// Generated by npm run images:responsive. Do not edit manually.\nexport default '
    + JSON.stringify(manifest, null, 4) + '\n')
